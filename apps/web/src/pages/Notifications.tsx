import { useState } from 'react';
import { get, patch, post } from '../services/api';
import { usePaged } from '../hooks/usePaged';
import { PageHead, Empty, Loading, Pager } from '../components/ui';

interface Row { _id: string; title: string; message: string; type: string; readAt: string | null; createdAt: string; }

export function Notifications(): JSX.Element {
  const [filter, setFilter] = useState('');
  const { rows, page, setPage, totalPages, loading, error, reload } = usePaged<Row>(`/notifications?${filter ? `status=${filter}&` : ''}limit=15`, filter);
  const [msg, setMsg] = useState<string | null>(null);

  return (
    <div>
      <PageHead
        title="Notifications"
        sub="Generated by task assignment, status, and project membership workflows."
        actions={<button className="btn" onClick={() => { void post('/notifications/read-all', {}).then(() => { setMsg('All marked read.'); reload(); }); }}>Mark all read</button>}
      />
      {msg ? <div className="card" style={{ marginBottom: 12 }}>{msg}</div> : null}
      <div className="toolbar">
        <select className="select" value={filter} onChange={(e) => setFilter(e.target.value)} aria-label="Filter notifications">
          <option value="">All</option>
          <option value="unread">Unread only</option>
        </select>
        <button className="btn" onClick={() => void get('/notifications').then(() => reload())}>Refresh</button>
      </div>
      {loading ? <Loading /> : error ? <div className="form-error">{error}</div> : rows.length === 0 ? <Empty text="No notifications." /> : (
        <div className="grid">
          {rows.map((n) => (
            <div className="card" key={n._id} style={{ opacity: n.readAt ? 0.65 : 1 }}>
              <strong>{n.title}</strong> <span style={{ color: 'var(--muted)', fontSize: 12 }}>{n.type} · {new Date(n.createdAt).toLocaleString()}</span>
              <p style={{ margin: '6px 0' }}>{n.message}</p>
              {!n.readAt ? <button className="btn small" onClick={() => { void patch(`/notifications/${n._id}/read`, {}).then(() => reload()); }}>Mark read</button> : <span style={{ fontSize: 12, color: 'var(--muted)' }}>Read</span>}
            </div>
          ))}
        </div>
      )}
      <Pager page={page} totalPages={totalPages} onPage={setPage} />
    </div>
  );
}
